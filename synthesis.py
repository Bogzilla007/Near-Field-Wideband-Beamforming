def build_robustness_figure(sources: dict):
    stage13 = sources["stage13_multipath"]
    stage10 = sources["stage10_noise"]

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5))

    # Left: multipath (Stage 13)
    ax = axes[0]
    summary = stage13[stage13.k_db != -999].groupby("k_db").gain_loss_conventional_db.mean().sort_index()
    los_only = stage13[stage13.k_db == -999].gain_loss_conventional_db.mean()
    ax.plot(summary.index, summary.values, marker="o", label="conventional (multipath)")
    ax.axhline(los_only, color="k", linestyle="--", label=f"pure LOS ({los_only:.2f} dB)")
    ax.set_xlabel("Rician K-factor (dB)")
    ax.set_ylabel("Gain loss vs. combined (dB)")
    ax.set_title("Multipath (Stage 13):\nadvantage barely erodes")
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    # Right: BER at 2 operating points (Stage 10), r_frac=0.05
    ax = axes[1]
    sub = stage10[stage10.r_frac_rayleigh == 0.05]
    operating_points = [-20, -35]
    x = np.arange(len(operating_points))
    width = 0.35
    for i, mode in enumerate(["conventional", "combined"]):
        vals = [sub[(sub.snr_in_db == snr) & (sub.beamformer == mode)].iloc[0].ber
                for snr in operating_points]
        ax.bar(x + (i - 0.5) * width, vals, width, label=mode)
    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels([f"{snr} dB\n(clean)" if snr == -20 else f"{snr} dB\n(garbage)" for snr in operating_points])
    ax.set_ylabel("BER (QPSK)")
    ax.set_title("Noise (Stage 10):\nsame dB gap, wildly different BER impact")
    ax.legend()
    ax.grid(True, axis="y", alpha=0.3)

    plt.suptitle("Stage 15, Slice 2: The core advantage survives independent real-world impairments", y=1.03)
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, "stage15_robustness.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)


