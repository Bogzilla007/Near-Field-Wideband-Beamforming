def load_or_regenerate(filename: str, regenerate_fn) -> pd.DataFrame:
    """Load results/{filename} if present; otherwise call regenerate_fn()
    (which must call the SAME already-validated function the original
    stage used) and save the result for next time.
    """
    path = os.path.join(RESULTS_DIR, filename)
    if os.path.exists(path):
        return pd.read_csv(path)
    print(f"  [synthesis] {filename} not found, regenerating via original stage's function...")
    df = regenerate_fn()
    df.to_csv(path, index=False)
    return df


