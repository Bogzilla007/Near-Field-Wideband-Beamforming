def build_bug_to_feature_figure(sources: dict):
    fine_sweep = sources["fine_sweep"]
    stage11 = sources["stage11_multiuser"]

    sub_fs = fine_sweep[(fine_sweep.N == 1024) & (fine_sweep.bandwidth == 2e9)].sort_values("r_frac_rayleigh")
    sub_fs = sub_fs[sub_fs.r_frac_rayleigh.isin([0.02, 0.05, 0.1])]

    sub_mu = stage11[stage11.condition == "B_wideband_combined"].sort_values("r1_frac_rayleigh")

    fig, ax1 = plt.subplots(figsize=(9, 6))
    ax2 = ax1.twinx()

    l1, = ax1.plot(sub_fs.r_frac_rayleigh, sub_fs.gain_loss_conventional_db,
                    "o-", color="firebrick", label="Conventional gain-loss (Stage 5/8, 'bug')")
    l2, = ax2.plot(sub_mu.r1_frac_rayleigh, sub_mu.separation_db,
                    "s-", color="seagreen", label="Multi-user separation (Stage 11, 'feature')")

    ax1.set_xscale("log")
    ax1.set_xlabel("r / Rayleigh distance")
    ax1.set_ylabel("Conventional gain-loss vs. combined (dB)", color="firebrick")
    ax2.set_ylabel("Multi-user separation, combined mode (dB)", color="seagreen")
    ax1.tick_params(axis="y", colors="firebrick")
    ax2.tick_params(axis="y", colors="seagreen")

    ax1.legend(handles=[l1, l2], loc="upper right", fontsize=8)
    plt.title("Stage 15, Slice 3: Same near-field regime, opposite framing\n"
              "(N=1024, deep near-field: worst for single-user angle-only beamforming,\n"
              "best for near-field-aware multi-user range discrimination)")
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, "stage15_bug_to_feature.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)


def build_all_figures(sources: dict):
    os.makedirs(FIGURES_DIR, exist_ok=True)
    build_decision_map(sources)
    build_robustness_figure(sources)
    build_bug_to_feature_figure(sources)