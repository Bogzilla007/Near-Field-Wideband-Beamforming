def classify_severity(loss_db: float) -> str:
    """Safe/Marginal/Severe bands using THIS project's own established
    thresholds: 3dB is Stage 5's failure threshold; 8dB is the coarse
    sweep's 'hardest point' reference used in Stage 5's own hard-gate
    checks. Not new/arbitrary thresholds."""
    if loss_db < 3.0:
        return "Safe"
    elif loss_db < 8.0:
        return "Marginal"
    else:
        return "Severe"


def build_decision_map(sources: dict):
    fine_sweep = sources["fine_sweep"]
    stage6 = sources["stage6_recovery"]
    stage9 = sources["stage9_quantization"]
    stage14 = sources["stage14_hybrid"]

    facet_bandwidths = [10e6, 400e6, 4e9]  # same 3 facets Stage 5/8 used
    fig, axes = plt.subplots(1, len(facet_bandwidths), figsize=(18, 6), sharey=True)

    severity_colors = {"Safe": 0, "Marginal": 1, "Severe": 2}
    cmap = plt.matplotlib.colors.ListedColormap(["#2a9d8f", "#e9c46a", "#e76f51"])

    for ax, bw in zip(axes, facet_bandwidths):
        sub = fine_sweep[fine_sweep.bandwidth == bw].copy()
        sub["severity_code"] = sub.gain_loss_conventional_db.apply(
            lambda x: severity_colors[classify_severity(x)]
        )
        pivot = sub.pivot(index="r_frac_rayleigh", columns="N", values="severity_code").sort_index()
        X = pivot.columns.values.astype(float)
        Y = pivot.index.values.astype(float)
        Z = pivot.values

        ax.pcolormesh(X, Y, Z, shading="nearest", cmap=cmap, vmin=0, vmax=2)
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.axhline(1.0, color="white", linestyle="--", linewidth=1, alpha=0.7)
        ax.set_xlabel("Array size N")
        ax.set_title(f"Bandwidth = {bw/1e6:.0f} MHz")

        # Overlay: exact tested remediation points, only at BW=4GHz where
        # Stages 6/9/14 all did their worst-region testing.
        if bw == 4e9:
            for _, row in stage6.iterrows():
                ax.plot(512, row.r_frac_rayleigh, "k^", markersize=10, markeredgecolor="white")
            ax.annotate(
                "Combined corrector:\nfull recovery\n(11.2-13.4 dB, Stage 6)",
                xy=(512, 0.05), xytext=(60, 0.015),
                fontsize=7, color="white",
                arrowprops=dict(arrowstyle="->", color="white"),
            )
            eff_2bit = stage9[(stage9.r_frac_rayleigh == 0.05) & (stage9.n_bits == 2)].iloc[0].recovery_efficiency
            ax.annotate(
                f"2-bit quantized:\n{eff_2bit*100:.0f}% recovery eff.\n(Stage 9)",
                xy=(512, 0.05), xytext=(12, 0.4),
                fontsize=7, color="white",
                arrowprops=dict(arrowstyle="->", color="white"),
            )
            loss_16rf = stage14[stage14.n_rf == 16].iloc[0].gain_loss_db
            ax.annotate(
                f"16-RF hybrid:\n{loss_16rf:.3f} dB from ideal\n(Stage 14)",
                xy=(512, 0.1), xytext=(180, 3.0),
                fontsize=7, color="white",
                arrowprops=dict(arrowstyle="->", color="white"),
            )

    axes[0].set_ylabel("Distance / Rayleigh distance")
    from matplotlib.patches import Patch
    legend_elems = [Patch(facecolor=c, label=l) for l, c in
                    zip(["Safe (<3dB)", "Marginal (3-8dB)", "Severe (>8dB)"],
                        ["#2a9d8f", "#e9c46a", "#e76f51"])]
    fig.legend(handles=legend_elems, loc="upper center", ncol=3, bbox_to_anchor=(0.5, 1.05))
    plt.suptitle(
        "Stage 15, Slice 1: Failure severity map with validated fixes overlaid\n"
        "(overlay markers = exact tested points only, NOT extrapolated across the grid)",
        y=1.12,
    )
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURES_DIR, "stage15_decision_map.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)


